// Writes the wrangler config that deploy-cloudflare deploys with, and that
// preview-workers uploads each preview version with:
//
//   node write-wrangler-config.js <file> <worker-name> <assets-directory>
//
// Generated per run rather than committed per repo, so consumers stay
// config-free. Paths in a wrangler config resolve against the config file,
// which lives in RUNNER_TEMP, so the assets directory must be absolute.
//
// The action harness runs this same file through each action's pinned
// wrangler with --dry-run, so a wrangler bump that stops accepting this shape
// fails CI rather than a consumer's deploy.
const fs = require("fs");
const path = require("path");

const [file, name, directory] = process.argv.slice(2);
if (!file || !name || !directory || !path.isAbsolute(directory)) {
  console.error("usage: node write-wrangler-config.js <file> <worker-name> <absolute-assets-directory>");
  process.exit(2);
}

const config = {
  name,
  compatibility_date: "2026-09-01",
  assets: { directory },
  // The production URL deploy-cloudflare constructs and probes.
  workers_dev: true,
  // Needed for deploy-cloudflare's `alias`. Previews sit behind the same
  // Access application when it is set to All traffic, and the alias is
  // probed after upload.
  //
  // Only `wrangler deploy` applies these two. preview-workers' `versions
  // upload` leaves the Worker's settings as they are, so its Worker must
  // have its preview URLs on already.
  preview_urls: true,
};

fs.writeFileSync(
  file,
  "// Generated by quantecon/actions for one run.\n" +
    JSON.stringify(config, null, 2) + "\n"
);
